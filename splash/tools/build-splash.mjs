// Build splash.js: core + scenes + boot inside one IIFE, with the whale glyph inlined from the
// shipped brand SVG. Also stages the result into asar-src/renderer for previews.
//
// Lab builds (for working on scenes without touching the shipped splash.js):
//   node tools/build-splash.mjs --lab name1,name2   → preview/lab/<name>/ with core + that one scene + boot
// and every build also writes preview/lab/_all/ (all shipped scenes). A lab folder holds splash.js,
// splash.css and a splash.html that loads preview/lab-clock.js first, so preview/lab.html can step the
// splash on a virtual clock (exact frames, frame-cost timing).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const svg = fs.readFileSync(path.join(root, 'asar-src/renderer/assets/welcome-brand.svg'), 'utf8');
const m = svg.match(/<g clip-path="url\(#clip0_2141_5628\)">\s*<path d="([^"]+)"/);
if (!m) throw new Error('whale path not found');

const src = path.join(root, 'splash/src');
const SCENE_ORDER = ['construct', 'orbit', 'signal', 'weave', 'pulsar', 'current', 'spline', 'hanzi', 'shadow', 'echo', 'chladni', 'bathy'];
const banner = '// DeepSeek Harness launch splash — generated by tools/build-splash.mjs from splash/src. Do not edit.\n';
const read = (f) => fs.readFileSync(path.join(src, f), 'utf8');
const bundle = (scenes) => {
  const parts = [read('core.js'), ...scenes.map((n) => read(`scenes/${n}.js`)), read('boot.js')];
  return `${banner}(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`.replace('__WHALE_PATH__', m[1]);
};

function writeLab(dir, js) {
  const out = path.join(root, 'preview/lab', dir);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'splash.js'), js);
  fs.copyFileSync(path.join(root, 'splash/splash.css'), path.join(out, 'splash.css'));
  const html = fs.readFileSync(path.join(root, 'splash/splash.html'), 'utf8')
    .replace('<script src="splash.js" defer></script>', '<script src="../../lab-clock.js"></script>\n    <script src="splash.js" defer></script>');
  if (!html.includes('lab-clock.js')) throw new Error('splash.html: script tag not found');
  fs.writeFileSync(path.join(out, 'splash.html'), html);
}

const labArg = process.argv.indexOf('--lab');
if (labArg > 0) {
  const names = (process.argv[labArg + 1] || '').split(',').filter(Boolean);
  if (!names.length) throw new Error('--lab needs scene names');
  for (const n of names) {
    const js = bundle([n]);
    writeLab(n, js);
    console.log(`lab/${n}/splash.js built (${js.length} bytes)`);
  }
} else {
  const out = bundle(SCENE_ORDER);
  fs.writeFileSync(path.join(root, 'splash/splash.js'), out);
  for (const f of ['splash.html', 'splash.css', 'splash.js']) {
    fs.copyFileSync(path.join(root, 'splash', f), path.join(root, 'asar-src/renderer', f));
  }
  writeLab('_all', out);
  console.log(`splash.js built (${SCENE_ORDER.length} scenes, ${out.length} bytes)`);
}
